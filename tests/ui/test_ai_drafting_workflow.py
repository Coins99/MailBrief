async def test_cancelling_while_preparing_shows_no_preview(
    window: MainWindow, backend: FakeBackend
) -> None:
    await open_note(window)
    await open_ai(window)
    editor = window.draft_editor
    real_prepare = backend.prepare_drafting

    async def prepare_then_cancel(public_id: str, options: object) -> object:
        plan = await real_prepare(public_id, options)  # type: ignore[arg-type]
        editor.ai_panel.cancel_button.click()
        return plan

    backend.prepare_drafting = prepare_then_cancel  # type: ignore[assignment,method-assign]
    editor.ai_panel.continue_button.click()
    await settle(window)

    assert editor.ai_panel.preview.isHidden()
    assert window._drafting_plan is None


