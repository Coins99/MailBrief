async def test_cancelling_a_generation_stops_it_and_writes_nothing(
    window: MainWindow, backend: FakeBackend
) -> None:
    backend.ai_consent = True
    backend.ai_gate = asyncio.Event()
    await open_note(window)
    editor = window.draft_editor
    await preview(window)
    editor.ai_panel.send_button.click()
    for _ in range(5):
        await asyncio.sleep(0)
    assert editor.status.text() == "Writing with Groq…"

    editor.ai_panel.cancel_button.click()
    await settle(window)

    assert editor.body.toPlainText() == "My notes"
    assert editor.status.text() == "Cancelled. Your text is unchanged."
    public_id = editor.draft.public_id  # type: ignore[union-attr]
    assert backend.drafts[public_id].body == "My notes"


