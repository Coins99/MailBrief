async def test_first_use_previews_asks_for_consent_then_writes_a_new_version(
    window: MainWindow, backend: FakeBackend
) -> None:
    await open_note(window)
    editor = window.draft_editor
    await open_ai(window)
    editor.ai_panel.instructions.setPlainText("Make it a list.")

    editor.ai_panel.continue_button.click()
    assert not editor._fields.isEnabled()  # The text is frozen until the end.
    await settle(window)

    (call,) = ai_calls(backend, "prepare_drafting")
    assert call[2].instructions == "Make it a list."  # type: ignore[attr-defined]
    assert backend.draft_calls[-1][0] == "autosave_draft"  # Saved before the preview.
    preview_text = editor.ai_panel.preview_text.toPlainText()
    assert preview_text.startswith("MailBrief will send these parts to Groq (fake-model)")
    assert "- Your current text: title and body: 12 characters" in preview_text
    assert "Enable Zero Data Retention first." in preview_text
    assert not editor.ai_panel.send_button.isEnabled()
    editor.ai_panel.agree_box.setChecked(True)
    editor.ai_panel.send_button.click()
    assert editor.status.text() == "Writing with Groq…"
    await settle(window)

    assert editor.body.toPlainText() == "Generated text"
    assert editor.status.text() == "New version v3 from Groq; your previous text is version v2."
    assert editor.missing_line.text() == "Missing context to check: the delivery date"
    assert editor._fields.isEnabled() and not editor.ai_active()
    assert backend.ai_consent
    editor.versions_button.click()
    await settle(window)
    assert "generated by fake-model (warm, short)" in editor.versions_list.item(0).text()


async def test_later_generations_send_without_the_consent_box(
    window: MainWindow, backend: FakeBackend
) -> None:
    backend.ai_consent = True
    await open_note(window)
    editor = window.draft_editor

    await preview(window)
    assert editor.ai_panel.agree_box.isHidden()
    editor.ai_panel.send_button.click()
    await settle(window)
    assert not editor.ai_panel.isHidden()  # Still open, ready to write again.
    editor.ai_panel.continue_button.click()
    await settle(window)
    editor.ai_panel.send_button.click()
    await settle(window)

    assert len(ai_calls(backend, "generate_draft")) == 2
    assert editor.draft is not None
    versions = backend.versions[editor.draft.public_id]
    assert len([v for v in versions if v.origin == "generated"]) == 2


async def test_a_declined_or_failed_generation_leaves_the_text(
    window: MainWindow, backend: FakeBackend
) -> None:
    backend.ai_consent = True
    await open_note(window)
    editor = window.draft_editor
    backend.ai_outcome = DraftingOutcome(status=DraftingStatus.FAILED, error_code="AI_TIMEOUT")

    await preview(window)
    editor.ai_panel.send_button.click()
    await settle(window)

    assert editor.body.toPlainText() == "My notes"
    assert editor.status.text() == "Groq did not respond in time; retry later."
    assert editor._fields.isEnabled()

    backend.ai_outcome = DraftingOutcome(status=DraftingStatus.FAILED, error_code="AI_REFUSED")
    await preview(window)
    editor.ai_panel.send_button.click()
    await settle(window)
    assert editor.body.toPlainText() == "My notes"
    assert editor.status.text() == (
        "Groq declined to write this draft. Change the instructions or context and try again."
    )

    backend.ai_outcome = DraftingOutcome(status=DraftingStatus.DECLINED)
    await preview(window)
    editor.ai_panel.send_button.click()
    await settle(window)
    assert editor.status.text() == "Nothing was sent: AI drafting needs your consent first."


