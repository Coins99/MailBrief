async def settle(window: MainWindow) -> None:
    await window.draft_writes.drain()


async def open_note(window: MainWindow, body: str = "My notes") -> None:
    await window.initialize()
    window.drafts_panel.new_menu.actions()[1].trigger()
    assert window.task is not None
    await window.task
    window.draft_editor.body.setPlainText(body)


async def open_ai(window: MainWindow) -> None:
    window.draft_editor.ai_button.click()
    await settle(window)


async def preview(window: MainWindow) -> None:
    await open_ai(window)
    window.draft_editor.ai_panel.continue_button.click()
    await settle(window)


def ai_calls(backend: FakeBackend, name: str) -> list[tuple[object, ...]]:
    return [call for call in backend.ai_calls if call[0] == name]


async def test_the_button_needs_a_groq_key(window: MainWindow, backend: FakeBackend) -> None:
    backend.ai_ready = False
